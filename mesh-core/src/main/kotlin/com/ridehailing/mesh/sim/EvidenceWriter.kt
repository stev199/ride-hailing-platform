package com.ridehailing.mesh.sim

import java.io.File
import java.time.Instant

/**
 * GATE 3 evidence output (Part C): metrics table (markdown), full metrics JSON and
 * SVG charts into /docs/evidence/mesh-sim/. Zero-dependency SVG keeps the module
 * free of chart libraries.
 */
object EvidenceWriter {

    private val keyColumns = listOf(
        "deliveryRatio", "requestDeliveryRatio", "latencyP95Ms", "transmissionsPerDelivered",
        "txPerNode", "floodCompletionRatio", "parityRatio", "maxFailoverMs",
    )

    fun writeAll(results: List<ScenarioResult>, dir: File) {
        dir.mkdirs()
        File(dir, "metrics.json").writeText(BaselineCheck.toJson(results))
        File(dir, "metrics.md").writeText(markdown(results))
        val charts = File(dir, "charts")
        charts.mkdirs()
        File(charts, "delivery-ratio.svg").writeText(
            barChart(
                "Delivery ratio per scenario",
                results.map { it.name to (it.metrics["deliveryRatio"] ?: it.metrics["deliveryRatioDrivingDense"] ?: 0.0) },
                yMax = 1.0,
            ),
        )
        File(charts, "latency-p95.svg").writeText(
            barChart(
                "Latency p95 (ms) per scenario (0 when not measured)",
                results.map { it.name to (it.metrics["latencyP95Ms"] ?: 0.0) },
                yMax = 3_000.0,
            ),
        )
        File(charts, "transmissions.svg").writeText(
            barChart(
                "Transmission efficiency per scenario",
                results.map {
                    it.name to (it.metrics["transmissionsPerDelivered"] ?: it.metrics["txPerNode"] ?: it.metrics["stormTxRatio"] ?: 0.0)
                },
                yMax = 5.0,
            ),
        )
    }

    private fun markdown(results: List<ScenarioResult>): String = buildString {
        append("# Mesh simulation suite (GATE 3) - metrics\n\n")
        append("Deterministic (fixed seeds, virtual time). Regenerated by `gradle :mesh-core:simReport`.\n\n")
        append("| Scenario | Pass | " + keyColumns.joinToString(" | ") + " |\n")
        append("|---|---|" + keyColumns.joinToString("") { "---|" } + "\n")
        for (r in results) {
            val pass = if (r.failures().isEmpty()) "YES" else "NO"
            val cells = keyColumns.joinToString(" | ") { c ->
                r.metrics[c]?.let { fmt(it) } ?: "-"
            }
            append("| ${r.name} | $pass | $cells |\n")
        }
        append("\n## Notes and model choices\n\n")
        for (r in results) {
            append("### ${r.name} (seed ${r.seed})\n\n")
            for (n in r.notes) append("- $n\n")
            append("\nAll metrics:\n\n")
            append("| Metric | Value |\n|---|---|\n")
            for ((k, v) in r.metrics) append("| $k | ${fmt(v)} |\n")
            append("\n")
        }
        append("Generated: ${Instant.now()}\n")
    }

    private fun fmt(v: Double): String =
        if (v == v.toLong().toDouble()) v.toLong().toString() else "%.3f".format(v)

    /** Simple horizontal bar chart; labels on the left, value at the bar end. */
    private fun barChart(title: String, data: List<Pair<String, Double>>, yMax: Double): String {
        val rowH = 26
        val labelW = 210
        val chartW = 520
        val width = labelW + chartW + 60
        val height = 50 + data.size * rowH
        val sb = StringBuilder()
        sb.append("<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"$width\" height=\"$height\" font-family=\"monospace\" font-size=\"12\">\n")
        sb.append("<rect width=\"$width\" height=\"$height\" fill=\"white\"/>\n")
        sb.append("<text x=\"10\" y=\"22\" font-weight=\"bold\">$title</text>\n")
        data.forEachIndexed { i, (label, value) ->
            val y = 40 + i * rowH
            val w = (value.coerceIn(0.0, yMax) / yMax * chartW).toInt()
            sb.append("<text x=\"8\" y=\"${y + 13}\">${label.take(30)}</text>\n")
            sb.append("<rect x=\"$labelW\" y=\"$y\" width=\"$w\" height=\"16\" fill=\"#2563eb\"/>\n")
            sb.append("<text x=\"${labelW + w + 6}\" y=\"${y + 13}\">${fmt(value)}</text>\n")
        }
        sb.append("</svg>\n")
        return sb.toString()
    }
}
